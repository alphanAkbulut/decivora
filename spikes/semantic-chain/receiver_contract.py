"""Offline receiver shape/source guard. Frozen RECEIVER-001 evaluator is unchanged.

The emitted schema uses a deliberately small JSON Schema subset. shape_check is
only its local interpreter, not a general JSON Schema or provider validator.
"""
import argparse
import json
from pathlib import Path

from protocol import canonical, digest, strict_json
from receiver_smoke import ACTION_TYPES, ANSWER_STATES, FORMAT, check_request, validate_response

GUARD_VERSION = 'receiver-source-guard-1'


def obj(properties):
    return dict(type='object', properties=properties, required=list(properties), additionalProperties=False)


def arr(items, maximum=16):
    return dict(type='array', items=items, maxItems=maximum)


def schema_for(request):
    check_request(request)
    string = dict(type='string', minLength=1)
    optional_string = dict(type=['string', 'null'], minLength=1)
    revision = dict(type=['integer', 'null'], minimum=1)
    readback = obj(dict(
        question_id=optional_string, question_revision=revision,
        question_state=dict(type='string', enum=['pending', 'resolved', 'unknown']),
        approved_real_decision=dict(type='boolean', const=False),
        task_verified=dict(type='boolean', const=False),
        upload_verification=dict(type='string', enum=['unknown', 'reported_only']),
        answer_states=arr(obj(dict(message_id=string, status=dict(type='string', enum=sorted(ANSWER_STATES))))),
        reported_test_results=arr(obj(dict(criterion_id=string,
            criterion_revision=dict(type='integer', minimum=1),
            result=dict(type='string', enum=['passed', 'failed', 'unknown', 'not_run']))))))
    action = obj(dict(type=dict(type='string', enum=sorted(ACTION_TYPES)),
                      message_id=string, question_id=optional_string))
    variants = []
    for view in request['views']:
        binding = view['binding']
        for status in ('ok', 'abstain'):
            variants.append(obj(dict(
                project_id=dict(type='string', const=binding['project_id']),
                package_digest=dict(type='string', const=binding['package_digest']),
                status=dict(type='string', const=status),
                readback=readback if status == 'ok' else dict(type='null'),
                next_actions=arr(action) if status == 'ok' else dict(type='array', maxItems=0))))
    result = obj(dict(format=dict(type='string', const=FORMAT),
                      request_id=dict(type='string', const=request['request_id']),
                      responses=arr(dict(oneOf=variants), maximum=2)))
    result['$schema'] = 'https://json-schema.org/draft/2020-12/schema'
    return result


def shape_check(value, schema, path='$'):
    """Only keywords generated by schema_for are supported; unknown ones fail closed."""
    allowed = {'$schema', 'type', 'properties', 'required', 'additionalProperties',
               'items', 'maxItems', 'minLength', 'minimum', 'const', 'enum', 'oneOf'}
    if set(schema) - allowed:
        raise ValueError('unsupported schema keyword at ' + path)
    if 'oneOf' in schema:
        matches = 0
        for branch in schema['oneOf']:
            try:
                shape_check(value, branch, path)
                matches += 1
            except ValueError:
                pass
        if matches != 1:
            raise ValueError('schema oneOf at ' + path)
    if 'type' in schema:
        types = schema['type'] if isinstance(schema['type'], list) else [schema['type']]
        checks = {'object': type(value) is dict, 'array': type(value) is list,
                  'string': type(value) is str, 'integer': type(value) is int,
                  'boolean': type(value) is bool, 'null': value is None}
        if any(t not in checks for t in types) or not any(checks[t] for t in types):
            raise ValueError('schema type at ' + path)
    if 'const' in schema and canonical(value) != canonical(schema['const']):
        raise ValueError('schema const at ' + path)
    if 'enum' in schema and canonical(value) not in {canonical(v) for v in schema['enum']}:
        raise ValueError('schema enum at ' + path)
    if type(value) is dict:
        props = schema.get('properties', {})
        if not set(schema.get('required', [])) <= set(value):
            raise ValueError('schema required at ' + path)
        if schema.get('additionalProperties') is False and set(value) - set(props):
            raise ValueError('schema extra field at ' + path)
        for key in value.keys() & props.keys():
            shape_check(value[key], props[key], path + '.' + key)
    if type(value) is list:
        if len(value) > schema.get('maxItems', len(value)):
            raise ValueError('schema maxItems at ' + path)
        for i, item in enumerate(value):
            if 'items' in schema:
                shape_check(item, schema['items'], path + '[' + str(i) + ']')
    if type(value) is str and len(value) < schema.get('minLength', 0):
        raise ValueError('schema minLength at ' + path)
    if type(value) is int and value < schema.get('minimum', value):
        raise ValueError('schema minimum at ' + path)


def source_check(row, view):
    if row['status'] == 'abstain':
        return  # No suggestions; completeness remains a separate evaluator result.
    rb = row['readback']
    question = view['fixture_state'].get('question')
    if question and (rb['question_id'], rb['question_revision'], rb['question_state']) != (
            question['question_id'], question['option_revision'], question['state']):
        raise ValueError('known current question must be preserved')
    candidates = {c['message_id']: c for c in view['answer_candidates']}
    if {a['message_id']: a['status'] for a in rb['answer_states']} != {
            mid: c['status'] for mid, c in candidates.items()}:
        raise ValueError('answer states differ from selected candidates')
    records = {r['message_id']: r for r in view['preserved_records']}
    if len(records) != len(view['preserved_records']):
        raise ValueError('multiple records per message unsupported by this guard')
    evidence = [dict(r['attributes']) for r in records.values() if r['kind'] == 'Evidence']
    if sorted(map(canonical, rb['reported_test_results'])) != sorted(map(canonical, evidence)):
        raise ValueError('reported tests differ from selected evidence')
    upload = any(r['kind'] == 'ImplementationClaim' and r['attributes'].get('claim_type') == 'upload'
                 for r in records.values())
    if rb['upload_verification'] != ('reported_only' if upload else 'unknown'):
        raise ValueError('upload state lacks selected evidence')
    seen = set()
    for action in row['next_actions']:
        mid = action['message_id']
        if mid not in records or mid in seen:
            raise ValueError('action must reference one preserved record once')
        seen.add(mid)
        record = records[mid]
        qid = None
        if record['kind'] == 'AnswerRecord':
            candidate = candidates.get(mid)
            if candidate is None:
                raise ValueError('answer has no source-bound candidate')
            state = candidate['status']
            qid = candidate['attributes'].get('question_id')
            if state == 'pending_trusted_selection':
                allowed = {'request_selection_confirmation'}
            elif state in ('needs_clarification', 'needs_question_context', 'conflicting_answers'):
                allowed = {'request_clarification'}
            else:
                allowed = {'preserve_history'}
        elif record['kind'] == 'ImplementationClaim' and record['attributes'].get('claim_type') == 'upload':
            allowed = {'request_target_verification'}
        elif record['kind'] == 'Evidence' and record['attributes']['result'] == 'not_run':
            allowed = {'request_test_execution_permission'}
        else:
            allowed = {'preserve_history'}
        if action['type'] not in allowed or action['question_id'] != qid:
            raise ValueError('action contradicts record status or question binding')


def validate(request, raw):
    schema = schema_for(request)
    output = strict_json(raw, max_bytes=32768)
    shape_check(output, schema)
    rows = validate_response(request, raw)  # Existing identity, duplicates and source guards.
    views = {v['binding']['project_id']: v for v in request['views']}
    for row in rows:
        source_check(row, views[row['project_id']])
    return dict(status='validated_review_only', guard_version=GUARD_VERSION,
                request_id=request['request_id'], schema_sha256=digest(schema),
                response_value_sha256=digest(output), response_coverage_complete=len(rows) == 2 and all(r['status'] == 'ok' for r in rows),
                canonical_mutations=0, model_dispatches=0, paid_api_calls=0)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['schema', 'validate'])
    parser.add_argument('--request', required=True, type=Path)
    parser.add_argument('--response', type=Path)
    args = parser.parse_args()
    request = strict_json(args.request.read_text())
    if args.action == 'schema':
        if args.response:
            parser.error('schema reads no response or oracle')
        result = schema_for(request)
    else:
        if not args.response:
            parser.error('validate needs a saved response')
        result = validate(request, args.response.read_text())
    print(json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False))
